import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { pathToFileURL } from 'node:url';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

// The Agent SDK is ESM and calls createRequire(import.meta.url) at load time.
// In a CommonJS bundle import.meta is empty, so give it a real file URL.
// Obsidian may not define __filename for plugins; any absolute path works
// because we always pass pathToClaudeCodeExecutable.
const importMetaShim = `var __importMetaUrl = require('url').pathToFileURL(
	typeof __filename !== 'undefined' ? __filename : require('path').join(process.cwd(), 'main.js'),
).href;
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner + importMetaShim,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((m) => `node:${m}`),
	],
	define: {
		'import.meta.url': '__importMetaUrl',
	},
	// Obsidian runs plugins in Electron's renderer, whose AbortSignal Node's
	// events.setMaxListeners rejects; the SDK calls it for every query.
	// The shim imports 'node:events', so it is not aliased to itself.
	alias: {
		events: './src/shims/node-events.ts',
	},
	// Same cause: the renderer's global timers return numbers, but the SDK calls
	// setTimeout(...).unref(). Bare timer calls in the bundle use Node's timers;
	// plugin code that wants browser timers calls window.setTimeout.
	inject: ['./src/shims/node-timers.ts'],
	platform: 'node',
	format: 'cjs',
	target: 'es2022',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	// Obsidian evaluates the plugin as "plugin:llm-sessions", which relative source paths
	// can't be resolved against. Absolute file URLs let DevTools and VS Code find src/*.ts.
	// Dev builds only: production has no source map, so no local paths ship.
	sourceRoot: prod ? undefined : `${pathToFileURL(process.cwd()).href}/`,
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
